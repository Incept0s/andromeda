#!/usr/bin/env bash
# Regenerates THIRD-PARTY-LICENSES.md: every Rust crate compiled into
# Andromeda (all targets, normal dependencies) with its licence.
set -euo pipefail
cd "$(dirname "$0")/.."
{
    echo "# Third-party Rust crates"
    echo
    echo "Generated by \`scripts/third-party.sh\` from \`cargo tree\`. Every crate"
    echo "below is compiled into Andromeda; all licences are compatible with"
    echo "GPL-3.0-or-later. The full licence texts ship inside each crate's source"
    echo "on [crates.io](https://crates.io)."
    echo
    echo "| Crate | Version | Licence |"
    echo "|-------|---------|---------|"
    cargo tree --workspace -e normal --target all --prefix none -f '{p}|{l}' 2>/dev/null \
        | sed 's/ (\*)//; s/ (proc-macro)//' \
        | grep -v '^andromeda' | grep -v '^$' | sort -u \
        | awk -F'|' '{split($1, a, " "); printf "| %s | %s | %s |\n", a[1], a[2], $2}'
} > THIRD-PARTY-LICENSES.md
echo "Wrote THIRD-PARTY-LICENSES.md ($(grep -c '^| [a-z0-9]' THIRD-PARTY-LICENSES.md) crates)"
